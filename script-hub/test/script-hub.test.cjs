const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = path.resolve(__dirname, '../..');
assert.ok(fs.existsSync(path.join(base, 'script-hub/src/script-hub-core.cjs')), 'the modular hub registry must exist');
const { normalizeHubEntry, createHubRegistry } = require('../src/script-hub-core.cjs');
const { registerTornScriptMenu } = require('../src/script-hub-adapter.cjs');
const origin = 'https://www.torn.com';
const meta = { id: 'gym-planner', name: 'Gym Planner', icon: 'gym', version: '3.37', url: origin + '/gym.php', actions: [{ id: 'open', label: 'Open planner' }] };
for (const patch of [{ id: 'bad id' }, { url: 'https://evil.example/gym.php' }, { url: 'javascript:alert(1)' }, { url: origin + '/gym.php?key=secret' }, { actions: [{ id: '__proto__', label: 'Bad' }] }]) {
  assert.equal(normalizeHubEntry({ ...meta, ...patch }, origin), null);
}
assert.deepEqual(normalizeHubEntry({ ...meta, apiKey: 'never-store', actions: [{ ...meta.actions[0], secret: 'never-store' }] }, origin), meta);
const registry = createHubRegistry(origin, [meta]);
assert.equal(registry.get(meta.id).active, false);
registry.register({ ...meta, name: 'Updated' });
registry.register(meta);
assert.equal(registry.entries().length, 1);
assert.equal(registry.get(meta.id).active, true);
assert.equal(JSON.stringify(registry.snapshot()).includes('active'), false);
for (let i = 0; i < 150; i++) registry.register({ ...meta, id: 'script-' + i });
assert.ok(registry.entries().length <= 100, 'catalog is bounded');
registry.forget(meta.id);
assert.equal(registry.get(meta.id), undefined);

const doc = new EventTarget();
const win = new EventTarget();
const send = (name, value) => {
  if (name === 'activate') value = { ...value, instance: registrations.at(-1)?.instance };
  doc.dispatchEvent(new CustomEvent('torn-script-hub:v1:' + name, { detail: JSON.stringify(value) }));
};
const registrations = [], results = [];
doc.addEventListener('torn-script-hub:v1:register', e => registrations.push(JSON.parse(e.detail)));
doc.addEventListener('torn-script-hub:v1:result', e => results.push(JSON.parse(e.detail)));
let opened = 0;
const dispose = registerTornScriptMenu(doc, win, meta, { open: () => { opened++; } });
assert.equal(registrations.length, 1, 'adapter announces before hub exists');
send('discover', {});
assert.equal(registrations.length, 2, 'hub starting later can discover adapter');
send('activate', { id: 'other', action: 'open', request: 'r1' });
send('activate', { id: meta.id, action: 'unknown', request: 'r2' });
assert.equal(opened, 0);
send('activate', { id: meta.id, action: 'open', request: 'r3' });
assert.equal(opened, 1);
assert.equal(results.at(-1).status, 'opened');
doc.dispatchEvent(new CustomEvent('torn-script-hub:v1:activate', { detail: '{bad json' }));
assert.equal(opened, 1);
win.dispatchEvent(new Event('pagehide'));
send('activate', { id: meta.id, action: 'open', request: 'r4' });
assert.equal(opened, 1, 'inactive adapter releases action listeners');
win.dispatchEvent(new Event('pageshow'));
send('activate', { id: meta.id, action: 'open', request: 'r5' });
assert.equal(opened, 2, 'back-forward restore rebinds once');
dispose();
send('discover', {});
assert.equal(registrations.length, 3);
const cleanup = registerTornScriptMenu(doc, win, meta, { open: () => false });
send('activate', { id: meta.id, action: 'open', request: 'r6' });
assert.equal(results.at(-1).status, 'not-ready');
cleanup();
const cleanupError = registerTornScriptMenu(doc, win, meta, { open: () => { throw new Error('sensitive details'); } });
send('activate', { id: meta.id, action: 'open', request: 'r7' });
assert.equal(results.at(-1).status, 'error');
assert.equal(JSON.stringify(results).includes('sensitive details'), false);
cleanupError();
const cleanupNavigate = registerTornScriptMenu(doc, win, meta, { open: () => 'navigate' });
send('activate', { id: meta.id, action: 'open', request: 'r8' });
assert.equal(results.at(-1).status, 'navigate', 'an active script can request its supported route without losing the chosen menu');
cleanupNavigate();
let duplicateOpens = 0;
const older = registerTornScriptMenu(doc, win, meta, { open: () => { duplicateOpens++; } });
const newer = registerTornScriptMenu(doc, win, meta, { open: () => { duplicateOpens++; } });
send('activate', { id: meta.id, action: 'open', request: 'duplicate-open' });
assert.equal(duplicateOpens, 1, 'only the latest adapter may open a duplicate script menu');
older();
send('activate', { id: meta.id, action: 'open', request: 'newer-open' });
assert.equal(duplicateOpens, 2, 'disposing an older registration cannot detach its replacement');
newer();
registry.register({ ...meta, instance: 'new-instance' });
registry.deactivate(meta.id, 'old-instance');
assert.equal(registry.get(meta.id).active, true, 'an old adapter cannot deactivate a replacement');
assert.equal(JSON.stringify(registry.snapshot()).includes('instance'), false, 'runtime ownership is not persisted');
console.log('PASS script hub registry, discovery, dispatch and lifecycle contracts');
