fs.writeFileSync(path.join(out,'Torn_Banker_Request_Hub.user.js'),source);fs.writeFileSync(path.join(out,'Torn_Banker_Request_Hub.meta.js'),metadata+'\n');
console.log('Built Banker Request Hub '+release.version+' (one bundled desktop/PDA script).');
